/**
 * Generates `src/generated/external-configs.ts` — the list of external rule-set
 * configs shown by the "External config" dropdown on the home & convert pages.
 *
 * Single source: repository `base/config/*.ini`, served at `/base/config/...`
 * after static export.
 *
 * Hooked into `dev` / `build` / `build:static` so the dropdown always mirrors
 * the config INIs actually shipped with the build.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptsDir = dirname(fileURLToPath(import.meta.url));
const wwwRoot = join(scriptsDir, '..');
const baseConfigDir = join(wwwRoot, '..', 'base', 'config');
const outFile = join(wwwRoot, 'src', 'generated', 'external-configs.ts');

/** Recursively list `*.ini` under `dir`, returning relative paths sorted by name. */
function listIniFiles(dir) {
  const found = [];
  if (!existsSync(dir)) return found;
  const walk = (current, relPrefix) => {
    for (const name of readdirSync(current)) {
      const full = join(current, name);
      if (statSync(full).isDirectory()) {
        walk(full, relPrefix ? `${relPrefix}/${name}` : name);
      } else if (name.toLowerCase().endsWith('.ini')) {
        found.push(relPrefix ? `${relPrefix}/${name}` : name);
      }
    }
  };
  walk(dir, '');
  return found.sort((a, b) => a.localeCompare(b, 'en'));
}

// Only the repository rule-library configs (base/config). After `build:static`
// these land in `dist/base/config` and are fetchable as `/base/config/<file>`.
const options = listIniFiles(baseConfigDir).map((rel) => ({
  value: `/base/config/${rel}`,
  label: rel,
  group: 'base/config',
}));

const header = `// AUTO-GENERATED by scripts/generate-external-config-list.mjs — DO NOT EDIT BY HAND.
// External rule-set configs bundled with the site (repo base/config).
// Regenerate with: pnpm dev | pnpm build | pnpm build:static

export interface ExternalConfigOption {
    /** Value sent to the converter as the config parameter. */
    value: string;
    /** File name shown in the dropdown. */
    label: string;
    /** optgroup label (directory the file ships in). */
    group: string;
}

export const EXTERNAL_CONFIG_OPTIONS: ExternalConfigOption[] = [
`;

const rows = options
  .map((o) => `    { value: ${JSON.stringify(o.value)}, label: ${JSON.stringify(o.label)}, group: ${JSON.stringify(o.group)} },`)
  .join('\n');

const footer = `];
`;

const out = header + rows + footer;
mkdirSync(dirname(outFile), { recursive: true });

if (existsSync(outFile) && readFileSync(outFile, 'utf8') === out) {
  console.log(`[config-list] Up to date (${options.length} config INIs)`);
} else {
  writeFileSync(outFile, out, 'utf8');
  console.log(`[config-list] Wrote ${options.length} config INIs -> ${outFile}`);
}
